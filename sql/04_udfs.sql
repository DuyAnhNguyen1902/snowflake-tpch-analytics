USE ROLE TPCH_ADMIN;
USE WAREHOUSE TPCH_WH;
USE DATABASE TPCH_ANALYTICS_DB;
USE SCHEMA UDFS;

-- UDF 1: classify a customer by total revenue.
CREATE OR REPLACE FUNCTION CLASSIFY_CUSTOMER_REVENUE(TOTAL_REVENUE NUMBER(15,2))
RETURNS VARCHAR
LANGUAGE SQL
IMMUTABLE
COMMENT = 'Classify customer into VIP/GOLD/SILVER/BRONZE/STANDARD by revenue'
AS
$$
  CASE
    WHEN TOTAL_REVENUE IS NULL THEN 'STANDARD'
    WHEN TOTAL_REVENUE >= 500000 THEN 'VIP'
    WHEN TOTAL_REVENUE >= 200000 THEN 'GOLD'
    WHEN TOTAL_REVENUE >= 100000 THEN 'SILVER'
    WHEN TOTAL_REVENUE >= 50000 THEN 'BRONZE'
    ELSE 'STANDARD'
  END
$$;

-- UDF 2: validate the TPC-H phone form CC-AAA-EEE-NNNN.
CREATE OR REPLACE FUNCTION IS_VALID_PHONE(PHONE VARCHAR)
RETURNS BOOLEAN
LANGUAGE SQL
IMMUTABLE
COMMENT = 'Validate TPC-H phone format NN-NNN-NNN-NNNN'
AS
$$
  PHONE IS NOT NULL
  AND REGEXP_LIKE(TRIM(PHONE), '^[0-9]{2}-[0-9]{3}-[0-9]{3}-[0-9]{4}$')
$$;

-- UDF 3: pragmatic email validation for analytics/data-quality checks.
CREATE OR REPLACE FUNCTION IS_VALID_EMAIL(EMAIL VARCHAR)
RETURNS BOOLEAN
LANGUAGE SQL
IMMUTABLE
COMMENT = 'Validate a practical local@domain.tld email shape'
AS
$$
  EMAIL IS NOT NULL
  AND REGEXP_LIKE(
    TRIM(EMAIL),
    '^[A-Za-z0-9.!#$%&''*+/=?^_`{|}~-]+@[A-Za-z0-9-]+(\\.[A-Za-z0-9-]+)+$'
  )
$$;

GRANT USAGE ON FUNCTION CLASSIFY_CUSTOMER_REVENUE(NUMBER) TO ROLE TPCH_ANALYST;
GRANT USAGE ON FUNCTION IS_VALID_PHONE(VARCHAR) TO ROLE TPCH_ANALYST;
GRANT USAGE ON FUNCTION IS_VALID_EMAIL(VARCHAR) TO ROLE TPCH_ANALYST;

-- Unit-style tests: expected values are shown in EXPECTED_RESULT.
WITH TESTS AS (
  SELECT 1 ID, 600000::NUMBER REVENUE, 'VIP' EXPECTED_RESULT UNION ALL
  SELECT 2, 200000, 'GOLD' UNION ALL
  SELECT 3, 100000, 'SILVER' UNION ALL
  SELECT 4, 50000, 'BRONZE' UNION ALL
  SELECT 5, 49999, 'STANDARD' UNION ALL
  SELECT 6, NULL, 'STANDARD'
)
SELECT ID, REVENUE, EXPECTED_RESULT,
       CLASSIFY_CUSTOMER_REVENUE(REVENUE) ACTUAL_RESULT,
       EXPECTED_RESULT = ACTUAL_RESULT AS TEST_PASSED
FROM TESTS ORDER BY ID;

WITH TESTS AS (
  SELECT '10-100-100-1000' VALUE, TRUE EXPECTED_RESULT UNION ALL
  SELECT '1-100-100-1000', FALSE UNION ALL
  SELECT NULL, FALSE
)
SELECT VALUE, EXPECTED_RESULT, IS_VALID_PHONE(VALUE) ACTUAL_RESULT,
       EXPECTED_RESULT = ACTUAL_RESULT AS TEST_PASSED
FROM TESTS;

WITH TESTS AS (
  SELECT 'analyst@example.com' VALUE, TRUE EXPECTED_RESULT UNION ALL
  SELECT 'bad-email', FALSE UNION ALL
  SELECT 'missing@tld', FALSE UNION ALL
  SELECT NULL, FALSE
)
SELECT VALUE, EXPECTED_RESULT, IS_VALID_EMAIL(VALUE) ACTUAL_RESULT,
       EXPECTED_RESULT = ACTUAL_RESULT AS TEST_PASSED
FROM TESTS;

-- Apply the revenue UDF to Gold data.
SELECT C_CUSTKEY, C_NAME, TOTAL_SPENT,
       CLASSIFY_CUSTOMER_REVENUE(TOTAL_SPENT) AS CALCULATED_TIER,
       CUSTOMER_TIER AS STORED_TIER
FROM GOLD.CUSTOMER_LTV
ORDER BY TOTAL_SPENT DESC
LIMIT 20;

