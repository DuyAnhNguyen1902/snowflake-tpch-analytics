-- -----------------------------------------------------------------------------
-- 3.1 Data profiling
-- -----------------------------------------------------------------------------

-- Row counts for all eight Bronze tables.
SELECT 'REGION' TABLE_NAME, COUNT(*) ROW_COUNT FROM STAGING.REGION
UNION ALL SELECT 'NATION', COUNT(*) FROM STAGING.NATION
UNION ALL SELECT 'CUSTOMER', COUNT(*) FROM STAGING.CUSTOMER
UNION ALL SELECT 'SUPPLIER', COUNT(*) FROM STAGING.SUPPLIER
UNION ALL SELECT 'PART', COUNT(*) FROM STAGING.PART
UNION ALL SELECT 'PARTSUPP', COUNT(*) FROM STAGING.PARTSUPP
UNION ALL SELECT 'ORDERS', COUNT(*) FROM STAGING.ORDERS
UNION ALL SELECT 'LINEITEM', COUNT(*) FROM STAGING.LINEITEM
ORDER BY TABLE_NAME;

-- Customers by country and region.
SELECT R.R_NAME AS REGION, N.N_NAME AS COUNTRY,
       COUNT(DISTINCT C.C_CUSTKEY) AS CUSTOMER_COUNT,
       ROUND(AVG(C.C_ACCTBAL), 2) AS AVG_ACCOUNT_BALANCE
FROM STAGING.CUSTOMER C
JOIN STAGING.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
JOIN STAGING.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
GROUP BY R.R_NAME, N.N_NAME
ORDER BY CUSTOMER_COUNT DESC, COUNTRY;

-- Order mix by status.
SELECT O_ORDERSTATUS,
       CASE O_ORDERSTATUS WHEN 'F' THEN 'FULFILLED' WHEN 'O' THEN 'OPEN'
         WHEN 'P' THEN 'PENDING' ELSE 'UNKNOWN' END AS STATUS_DESCRIPTION,
       COUNT(*) AS ORDER_COUNT,
       ROUND(SUM(O_TOTALPRICE), 2) AS TOTAL_ORDER_VALUE,
       ROUND(AVG(O_TOTALPRICE), 2) AS AVG_ORDER_VALUE
FROM STAGING.ORDERS
GROUP BY O_ORDERSTATUS
ORDER BY ORDER_COUNT DESC;

-- Top 10 products by quantity sold, with revenue after discount.
SELECT P.P_PARTKEY, P.P_NAME,
       SUM(L.L_QUANTITY) AS QUANTITY_SOLD,
       ROUND(SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)), 2) AS NET_REVENUE
FROM STAGING.LINEITEM L
JOIN STAGING.PART P ON L.L_PARTKEY = P.P_PARTKEY
GROUP BY P.P_PARTKEY, P.P_NAME
ORDER BY QUANTITY_SOLD DESC
LIMIT 10;

-- Monthly sales trend.
SELECT DATE_TRUNC('month', O_ORDERDATE) AS ORDER_MONTH,
       COUNT(*) AS ORDER_COUNT,
       ROUND(SUM(O_TOTALPRICE), 2) AS TOTAL_REVENUE,
       ROUND(AVG(O_TOTALPRICE), 2) AS AVG_ORDER_VALUE
FROM STAGING.ORDERS
GROUP BY ORDER_MONTH
ORDER BY ORDER_MONTH;

-- -----------------------------------------------------------------------------
-- 3.2 Data quality checks
-- Each query returns a violation count; a healthy result is zero unless noted.
-- -----------------------------------------------------------------------------

-- Required-field NULL checks.
SELECT 'REGION_REQUIRED_NULLS' CHECK_NAME,
       COUNT_IF(R_REGIONKEY IS NULL OR R_NAME IS NULL) VIOLATION_COUNT FROM STAGING.REGION
UNION ALL SELECT 'NATION_REQUIRED_NULLS',
       COUNT_IF(N_NATIONKEY IS NULL OR N_NAME IS NULL OR N_REGIONKEY IS NULL) FROM STAGING.NATION
UNION ALL SELECT 'CUSTOMER_REQUIRED_NULLS',
       COUNT_IF(C_CUSTKEY IS NULL OR C_NAME IS NULL OR C_NATIONKEY IS NULL) FROM STAGING.CUSTOMER
UNION ALL SELECT 'SUPPLIER_REQUIRED_NULLS',
       COUNT_IF(S_SUPPKEY IS NULL OR S_NAME IS NULL OR S_NATIONKEY IS NULL) FROM STAGING.SUPPLIER
UNION ALL SELECT 'PART_REQUIRED_NULLS',
       COUNT_IF(P_PARTKEY IS NULL OR P_NAME IS NULL) FROM STAGING.PART
UNION ALL SELECT 'PARTSUPP_REQUIRED_NULLS',
       COUNT_IF(PS_PARTKEY IS NULL OR PS_SUPPKEY IS NULL) FROM STAGING.PARTSUPP
UNION ALL SELECT 'ORDERS_REQUIRED_NULLS',
       COUNT_IF(O_ORDERKEY IS NULL OR O_CUSTKEY IS NULL OR O_ORDERDATE IS NULL) FROM STAGING.ORDERS
UNION ALL SELECT 'LINEITEM_REQUIRED_NULLS',
       COUNT_IF(L_ORDERKEY IS NULL OR L_LINENUMBER IS NULL OR L_PARTKEY IS NULL OR L_SUPPKEY IS NULL)
       FROM STAGING.LINEITEM
ORDER BY CHECK_NAME;

-- Duplicate business keys.
SELECT 'REGION_DUPLICATE_KEYS' CHECK_NAME, COUNT(*) VIOLATION_COUNT
FROM (SELECT R_REGIONKEY FROM STAGING.REGION GROUP BY R_REGIONKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'NATION_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT N_NATIONKEY FROM STAGING.NATION GROUP BY N_NATIONKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'CUSTOMER_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT C_CUSTKEY FROM STAGING.CUSTOMER GROUP BY C_CUSTKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'SUPPLIER_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT S_SUPPKEY FROM STAGING.SUPPLIER GROUP BY S_SUPPKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'PART_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT P_PARTKEY FROM STAGING.PART GROUP BY P_PARTKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'PARTSUPP_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT PS_PARTKEY, PS_SUPPKEY FROM STAGING.PARTSUPP GROUP BY PS_PARTKEY, PS_SUPPKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'ORDERS_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT O_ORDERKEY FROM STAGING.ORDERS GROUP BY O_ORDERKEY HAVING COUNT(*) > 1)
UNION ALL SELECT 'LINEITEM_DUPLICATE_KEYS', COUNT(*)
FROM (SELECT L_ORDERKEY, L_LINENUMBER FROM STAGING.LINEITEM GROUP BY L_ORDERKEY, L_LINENUMBER HAVING COUNT(*) > 1)
ORDER BY CHECK_NAME;

-- Referential integrity checks.
SELECT 'NATION_WITHOUT_REGION' CHECK_NAME, COUNT(*) VIOLATION_COUNT
FROM STAGING.NATION N LEFT JOIN STAGING.REGION R ON N.N_REGIONKEY=R.R_REGIONKEY
WHERE R.R_REGIONKEY IS NULL
UNION ALL SELECT 'CUSTOMER_WITHOUT_NATION', COUNT(*)
FROM STAGING.CUSTOMER C LEFT JOIN STAGING.NATION N ON C.C_NATIONKEY=N.N_NATIONKEY
WHERE N.N_NATIONKEY IS NULL
UNION ALL SELECT 'ORDER_WITHOUT_CUSTOMER', COUNT(*)
FROM STAGING.ORDERS O LEFT JOIN STAGING.CUSTOMER C ON O.O_CUSTKEY=C.C_CUSTKEY
WHERE C.C_CUSTKEY IS NULL
UNION ALL SELECT 'LINEITEM_WITHOUT_ORDER', COUNT(*)
FROM STAGING.LINEITEM L LEFT JOIN STAGING.ORDERS O ON L.L_ORDERKEY=O.O_ORDERKEY
WHERE O.O_ORDERKEY IS NULL
UNION ALL SELECT 'LINEITEM_WITHOUT_PART', COUNT(*)
FROM STAGING.LINEITEM L LEFT JOIN STAGING.PART P ON L.L_PARTKEY=P.P_PARTKEY
WHERE P.P_PARTKEY IS NULL
UNION ALL SELECT 'LINEITEM_WITHOUT_SUPPLIER', COUNT(*)
FROM STAGING.LINEITEM L LEFT JOIN STAGING.SUPPLIER S ON L.L_SUPPKEY=S.S_SUPPKEY
WHERE S.S_SUPPKEY IS NULL
ORDER BY CHECK_NAME;

-- Domain and date consistency.
SELECT 'INVALID_ORDER_STATUS' CHECK_NAME,
       COUNT_IF(O_ORDERSTATUS NOT IN ('F','O','P')) VIOLATION_COUNT FROM STAGING.ORDERS
UNION ALL SELECT 'NEGATIVE_ORDER_PRICE',
       COUNT_IF(O_TOTALPRICE < 0) FROM STAGING.ORDERS
UNION ALL SELECT 'INVALID_DISCOUNT',
       COUNT_IF(L_DISCOUNT < 0 OR L_DISCOUNT > 1) FROM STAGING.LINEITEM
UNION ALL SELECT 'INVALID_TAX',
       COUNT_IF(L_TAX < 0 OR L_TAX > 1) FROM STAGING.LINEITEM
UNION ALL SELECT 'NONPOSITIVE_QUANTITY',
       COUNT_IF(L_QUANTITY <= 0) FROM STAGING.LINEITEM
UNION ALL SELECT 'RECEIPT_BEFORE_SHIP',
       COUNT_IF(L_RECEIPTDATE < L_SHIPDATE) FROM STAGING.LINEITEM
UNION ALL SELECT 'COMMIT_AFTER_RECEIPT',
       COUNT_IF(L_COMMITDATE > L_RECEIPTDATE) FROM STAGING.LINEITEM
ORDER BY CHECK_NAME;

-- Silver/Gold reconciliation.
SELECT 'ORDERS_BRONZE_VS_SILVER' CHECK_NAME,
       (SELECT COUNT(*) FROM STAGING.ORDERS) EXPECTED_COUNT,
       (SELECT COUNT(*) FROM SILVER.ORDERS_SILVER) ACTUAL_COUNT
UNION ALL SELECT 'CUSTOMER_BRONZE_VS_SILVER',
       (SELECT COUNT(*) FROM STAGING.CUSTOMER),
       (SELECT COUNT(*) FROM SILVER.CUSTOMER_SILVER)
UNION ALL SELECT 'LINEITEM_BRONZE_VS_SILVER',
       (SELECT COUNT(*) FROM STAGING.LINEITEM),
       (SELECT COUNT(*) FROM SILVER.LINEITEM_SILVER)
UNION ALL SELECT 'CUSTOMER_SILVER_VS_LTV',
       (SELECT COUNT(*) FROM SILVER.CUSTOMER_SILVER),
       (SELECT COUNT(*) FROM GOLD.CUSTOMER_LTV);

-- -----------------------------------------------------------------------------
-- 3.3 Performance analysis
-- Run the EXPLAIN, then the SELECT. Open Query Profile in Snowsight and capture:
-- partitions scanned, bytes scanned, join type, spilling and operator timings.
-- -----------------------------------------------------------------------------
EXPLAIN USING TEXT
SELECT C.C_REGION_NAME, C.C_MKTSEGMENT,
       COUNT(DISTINCT O.O_ORDERKEY) AS ORDER_COUNT,
       SUM(O.O_TOTALPRICE) AS TOTAL_REVENUE
FROM SILVER.ORDERS_SILVER O
JOIN SILVER.CUSTOMER_SILVER C ON O.O_CUSTKEY = C.C_CUSTKEY
WHERE O.O_ORDERDATE >= '1995-01-01' AND O.O_ORDERDATE < '1996-01-01'
GROUP BY C.C_REGION_NAME, C.C_MKTSEGMENT
ORDER BY TOTAL_REVENUE DESC;

SELECT C.C_REGION_NAME, C.C_MKTSEGMENT,
       COUNT(DISTINCT O.O_ORDERKEY) AS ORDER_COUNT,
       SUM(O.O_TOTALPRICE) AS TOTAL_REVENUE
FROM SILVER.ORDERS_SILVER O
JOIN SILVER.CUSTOMER_SILVER C ON O.O_CUSTKEY = C.C_CUSTKEY
WHERE O.O_ORDERDATE >= '1995-01-01' AND O.O_ORDERDATE < '1996-01-01'
GROUP BY C.C_REGION_NAME, C.C_MKTSEGMENT
ORDER BY TOTAL_REVENUE DESC;

-- Query history for evidence and comparison. ACCOUNT_USAGE can lag; this
-- Information Schema function is suitable for recent project runs.
SELECT QUERY_ID, QUERY_TEXT, USER_NAME, ROLE_NAME, WAREHOUSE_NAME,
       EXECUTION_STATUS, TOTAL_ELAPSED_TIME, COMPILATION_TIME,
       EXECUTION_TIME, BYTES_SCANNED, ROWS_PRODUCED,
       START_TIME, END_TIME
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY(
  END_TIME_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP()),
  RESULT_LIMIT => 100
))
WHERE DATABASE_NAME = 'TPCH_ANALYTICS_DB'
ORDER BY START_TIME DESC;

-- PARTITIONS_SCANNED and PARTITIONS_TOTAL are not exposed by the
-- INFORMATION_SCHEMA.QUERY_HISTORY table function on every account. Read them
-- from Query Profile in Snowsight. The ACCOUNT_USAGE.QUERY_HISTORY view also
-- exposes them, but it can have latency and requires additional monitoring
-- privileges, so it is not used in the portable query above.

