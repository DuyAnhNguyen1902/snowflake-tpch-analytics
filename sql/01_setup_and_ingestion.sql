-- -----------------------------------------------------------------------------
-- C. File format and internal stage
-- TPC-H .tbl files are pipe-delimited and normally end with a trailing pipe.
-- CSV files with the same column order also work when they use a pipe delimiter.
-- -----------------------------------------------------------------------------
USE SCHEMA STAGING;

CREATE FILE FORMAT IF NOT EXISTS TPCH_PIPE_FORMAT
  TYPE = CSV
  FIELD_DELIMITER = '|'
  SKIP_HEADER = 0
  FIELD_OPTIONALLY_ENCLOSED_BY = NONE
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('', 'NULL', '\\N')
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  TRIM_SPACE = TRUE
  DATE_FORMAT = 'YYYY-MM-DD';

CREATE STAGE IF NOT EXISTS TPCH_DATA_STAGE
  FILE_FORMAT = TPCH_PIPE_FORMAT
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Internal stage for TPC-H source files';

GRANT READ, WRITE ON STAGE TPCH_DATA_STAGE TO ROLE TPCH_DEVELOPER;
GRANT USAGE ON FILE FORMAT TPCH_PIPE_FORMAT TO ROLE TPCH_DEVELOPER;

-- Upload with SnowSQL/Snowflake CLI, for example:
