CREATE OR REPLACE PROCEDURE GOLD.SP_CALCULATE_CUSTOMER_LTV()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO GOLD.CUSTOMER_LTV T
  USING (
    SELECT C.C_CUSTKEY, C.C_NAME, C.C_NATION_NAME, C.C_REGION_NAME,
      C.C_MKTSEGMENT, COUNT(O.O_ORDERKEY) AS TOTAL_ORDERS,
      COALESCE(SUM(O.O_TOTALPRICE), 0)::NUMBER(15,2) AS TOTAL_SPENT,
      COALESCE(AVG(O.O_TOTALPRICE), 0)::NUMBER(15,2) AS AVG_ORDER_VALUE,
      MIN(O.O_ORDERDATE) AS FIRST_ORDER_DATE,
      MAX(O.O_ORDERDATE) AS LAST_ORDER_DATE,
      DATEDIFF('day', MIN(O.O_ORDERDATE), MAX(O.O_ORDERDATE)) AS CUSTOMER_TENURE_DAYS,
      CASE
        WHEN COALESCE(SUM(O.O_TOTALPRICE),0) >= 500000 THEN 'VIP'
        WHEN COALESCE(SUM(O.O_TOTALPRICE),0) >= 200000 THEN 'GOLD'
        WHEN COALESCE(SUM(O.O_TOTALPRICE),0) >= 100000 THEN 'SILVER'
        WHEN COALESCE(SUM(O.O_TOTALPRICE),0) >= 50000 THEN 'BRONZE'
        ELSE 'STANDARD'
      END AS CUSTOMER_TIER,
      COALESCE(MAX(O.O_ORDERDATE) >= DATEADD('day', -90, CURRENT_DATE()), FALSE) AS IS_ACTIVE,
      CURRENT_TIMESTAMP() AS LOAD_TIMESTAMP
    FROM SILVER.CUSTOMER_SILVER C
    LEFT JOIN SILVER.ORDERS_SILVER O ON C.C_CUSTKEY = O.O_CUSTKEY
    GROUP BY C.C_CUSTKEY, C.C_NAME, C.C_NATION_NAME, C.C_REGION_NAME, C.C_MKTSEGMENT
  ) S
  ON T.C_CUSTKEY=S.C_CUSTKEY
  WHEN MATCHED THEN UPDATE SET
    T.C_NAME=S.C_NAME, T.C_NATION_NAME=S.C_NATION_NAME,
    T.C_REGION_NAME=S.C_REGION_NAME, T.C_MKTSEGMENT=S.C_MKTSEGMENT,
    T.TOTAL_ORDERS=S.TOTAL_ORDERS, T.TOTAL_SPENT=S.TOTAL_SPENT,
    T.AVG_ORDER_VALUE=S.AVG_ORDER_VALUE, T.FIRST_ORDER_DATE=S.FIRST_ORDER_DATE,
    T.LAST_ORDER_DATE=S.LAST_ORDER_DATE,
    T.CUSTOMER_TENURE_DAYS=S.CUSTOMER_TENURE_DAYS,
    T.CUSTOMER_TIER=S.CUSTOMER_TIER, T.IS_ACTIVE=S.IS_ACTIVE,
    T.LOAD_TIMESTAMP=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    C_CUSTKEY, C_NAME, C_NATION_NAME, C_REGION_NAME, C_MKTSEGMENT,
    TOTAL_ORDERS, TOTAL_SPENT, AVG_ORDER_VALUE, FIRST_ORDER_DATE,
    LAST_ORDER_DATE, CUSTOMER_TENURE_DAYS, CUSTOMER_TIER, IS_ACTIVE,
    LOAD_TIMESTAMP
  ) VALUES (
    S.C_CUSTKEY, S.C_NAME, S.C_NATION_NAME, S.C_REGION_NAME,
    S.C_MKTSEGMENT, S.TOTAL_ORDERS, S.TOTAL_SPENT, S.AVG_ORDER_VALUE,
    S.FIRST_ORDER_DATE, S.LAST_ORDER_DATE, S.CUSTOMER_TENURE_DAYS,
    S.CUSTOMER_TIER, S.IS_ACTIVE, S.LOAD_TIMESTAMP
  );
  RETURN 'CUSTOMER_LTV recalculated';
END;
$$;

CREATE OR REPLACE PROCEDURE GOLD.SP_CALCULATE_DAILY_SALES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO GOLD.DAILY_SALES_SUMMARY T
  USING (
    SELECT O_ORDERDATE AS SUMMARY_DATE, YEAR(O_ORDERDATE) AS ORDER_YEAR,
      MONTH(O_ORDERDATE) AS ORDER_MONTH, QUARTER(O_ORDERDATE) AS ORDER_QUARTER,
      COUNT(DISTINCT O_ORDERKEY) AS TOTAL_ORDERS,
      COUNT(DISTINCT O_CUSTKEY) AS TOTAL_CUSTOMERS,
      SUM(O_TOTALPRICE)::NUMBER(15,2) AS TOTAL_REVENUE,
      AVG(O_TOTALPRICE)::NUMBER(15,2) AS AVG_ORDER_VALUE,
      MIN(O_TOTALPRICE)::NUMBER(15,2) AS MIN_ORDER_VALUE,
      MAX(O_TOTALPRICE)::NUMBER(15,2) AS MAX_ORDER_VALUE,
      CURRENT_TIMESTAMP() AS LOAD_TIMESTAMP
    FROM SILVER.ORDERS_SILVER
    GROUP BY O_ORDERDATE
  ) S
  ON T.SUMMARY_DATE=S.SUMMARY_DATE
  WHEN MATCHED THEN UPDATE SET
    T.ORDER_YEAR=S.ORDER_YEAR, T.ORDER_MONTH=S.ORDER_MONTH,
    T.ORDER_QUARTER=S.ORDER_QUARTER, T.TOTAL_ORDERS=S.TOTAL_ORDERS,
    T.TOTAL_CUSTOMERS=S.TOTAL_CUSTOMERS, T.TOTAL_REVENUE=S.TOTAL_REVENUE,
    T.AVG_ORDER_VALUE=S.AVG_ORDER_VALUE, T.MIN_ORDER_VALUE=S.MIN_ORDER_VALUE,
    T.MAX_ORDER_VALUE=S.MAX_ORDER_VALUE, T.LOAD_TIMESTAMP=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    SUMMARY_DATE, ORDER_YEAR, ORDER_MONTH, ORDER_QUARTER, TOTAL_ORDERS,
    TOTAL_CUSTOMERS, TOTAL_REVENUE, AVG_ORDER_VALUE, MIN_ORDER_VALUE,
    MAX_ORDER_VALUE, LOAD_TIMESTAMP
  ) VALUES (
    S.SUMMARY_DATE, S.ORDER_YEAR, S.ORDER_MONTH, S.ORDER_QUARTER,
    S.TOTAL_ORDERS, S.TOTAL_CUSTOMERS, S.TOTAL_REVENUE,
    S.AVG_ORDER_VALUE, S.MIN_ORDER_VALUE, S.MAX_ORDER_VALUE,
    S.LOAD_TIMESTAMP
  );
  RETURN 'DAILY_SALES_SUMMARY recalculated';
END;
$$;

