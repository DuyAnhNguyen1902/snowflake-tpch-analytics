CREATE OR REPLACE PROCEDURE SILVER.SP_BRONZE_TO_SILVER_ORDERS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO SILVER.ORDERS_SILVER T
  USING (
    SELECT * EXCLUDE (RN)
    FROM (
      SELECT
        O_ORDERKEY, O_CUSTKEY, O_ORDERSTATUS,
        CASE O_ORDERSTATUS WHEN 'F' THEN 'FULFILLED' WHEN 'O' THEN 'OPEN'
          WHEN 'P' THEN 'PENDING' ELSE 'UNKNOWN' END AS O_ORDERSTATUS_DESC,
        O_TOTALPRICE, O_ORDERDATE,
        YEAR(O_ORDERDATE) AS O_ORDER_YEAR,
        MONTH(O_ORDERDATE) AS O_ORDER_MONTH,
        QUARTER(O_ORDERDATE) AS O_ORDER_QUARTER,
        O_ORDERPRIORITY,
        TRY_TO_NUMBER(REGEXP_SUBSTR(O_ORDERPRIORITY, '^[0-9]+')) AS O_PRIORITY_RANK,
        O_CLERK,
        TRY_TO_NUMBER(REGEXP_SUBSTR(O_CLERK, '[0-9]+$')) AS O_CLERK_ID,
        O_SHIPPRIORITY, O_COMMENT,
        'STAGING.ORDERS_STREAM' AS SOURCE_FILE,
        CURRENT_TIMESTAMP() AS FIRST_LOADED_AT,
        CURRENT_TIMESTAMP() AS LAST_UPDATED_AT,
        ROW_NUMBER() OVER (PARTITION BY O_ORDERKEY ORDER BY METADATA$ROW_ID DESC) AS RN
      FROM STAGING.ORDERS_STREAM
      WHERE METADATA$ACTION = 'INSERT'
    )
    WHERE RN = 1
  ) S
  ON T.O_ORDERKEY = S.O_ORDERKEY
  WHEN MATCHED THEN UPDATE SET
    T.O_CUSTKEY=S.O_CUSTKEY, T.O_ORDERSTATUS=S.O_ORDERSTATUS,
    T.O_ORDERSTATUS_DESC=S.O_ORDERSTATUS_DESC, T.O_TOTALPRICE=S.O_TOTALPRICE,
    T.O_ORDERDATE=S.O_ORDERDATE, T.O_ORDER_YEAR=S.O_ORDER_YEAR,
    T.O_ORDER_MONTH=S.O_ORDER_MONTH, T.O_ORDER_QUARTER=S.O_ORDER_QUARTER,
    T.O_ORDERPRIORITY=S.O_ORDERPRIORITY, T.O_PRIORITY_RANK=S.O_PRIORITY_RANK,
    T.O_CLERK=S.O_CLERK, T.O_CLERK_ID=S.O_CLERK_ID,
    T.O_SHIPPRIORITY=S.O_SHIPPRIORITY, T.O_COMMENT=S.O_COMMENT,
    T.SOURCE_FILE=S.SOURCE_FILE, T.LAST_UPDATED_AT=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    O_ORDERKEY, O_CUSTKEY, O_ORDERSTATUS, O_ORDERSTATUS_DESC, O_TOTALPRICE,
    O_ORDERDATE, O_ORDER_YEAR, O_ORDER_MONTH, O_ORDER_QUARTER,
    O_ORDERPRIORITY, O_PRIORITY_RANK, O_CLERK, O_CLERK_ID,
    O_SHIPPRIORITY, O_COMMENT, SOURCE_FILE, FIRST_LOADED_AT, LAST_UPDATED_AT
  ) VALUES (
    S.O_ORDERKEY, S.O_CUSTKEY, S.O_ORDERSTATUS, S.O_ORDERSTATUS_DESC,
    S.O_TOTALPRICE, S.O_ORDERDATE, S.O_ORDER_YEAR, S.O_ORDER_MONTH,
    S.O_ORDER_QUARTER, S.O_ORDERPRIORITY, S.O_PRIORITY_RANK, S.O_CLERK,
    S.O_CLERK_ID, S.O_SHIPPRIORITY, S.O_COMMENT, S.SOURCE_FILE,
    S.FIRST_LOADED_AT, S.LAST_UPDATED_AT
  );
  RETURN 'ORDERS_STREAM consumed and ORDERS_SILVER merged';
END;
$$;

CREATE OR REPLACE PROCEDURE SILVER.SP_BRONZE_TO_SILVER_CUSTOMERS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO SILVER.CUSTOMER_SILVER T
  USING (
    SELECT * EXCLUDE (RN)
    FROM (
      SELECT C.C_CUSTKEY, TRIM(C.C_NAME) AS C_NAME, TRIM(C.C_ADDRESS) AS C_ADDRESS,
        C.C_NATIONKEY, N.N_NAME AS C_NATION_NAME, N.N_REGIONKEY AS C_REGIONKEY,
        R.R_NAME AS C_REGION_NAME, C.C_PHONE, C.C_ACCTBAL,
        C.C_MKTSEGMENT, C.C_COMMENT, CURRENT_TIMESTAMP() AS LOAD_TIMESTAMP,
        ROW_NUMBER() OVER (PARTITION BY C.C_CUSTKEY ORDER BY C.METADATA$ROW_ID DESC) AS RN
      FROM STAGING.CUSTOMER_STREAM C
      LEFT JOIN STAGING.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
      LEFT JOIN STAGING.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
      WHERE C.METADATA$ACTION = 'INSERT'
    )
    WHERE RN = 1
  ) S
  ON T.C_CUSTKEY = S.C_CUSTKEY
  WHEN MATCHED THEN UPDATE SET
    T.C_NAME=S.C_NAME, T.C_ADDRESS=S.C_ADDRESS, T.C_NATIONKEY=S.C_NATIONKEY,
    T.C_NATION_NAME=S.C_NATION_NAME, T.C_REGIONKEY=S.C_REGIONKEY,
    T.C_REGION_NAME=S.C_REGION_NAME, T.C_PHONE=S.C_PHONE,
    T.C_ACCTBAL=S.C_ACCTBAL, T.C_MKTSEGMENT=S.C_MKTSEGMENT,
    T.C_COMMENT=S.C_COMMENT, T.LOAD_TIMESTAMP=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    C_CUSTKEY, C_NAME, C_ADDRESS, C_NATIONKEY, C_NATION_NAME,
    C_REGIONKEY, C_REGION_NAME, C_PHONE, C_ACCTBAL, C_MKTSEGMENT,
    C_COMMENT, LOAD_TIMESTAMP
  ) VALUES (
    S.C_CUSTKEY, S.C_NAME, S.C_ADDRESS, S.C_NATIONKEY, S.C_NATION_NAME,
    S.C_REGIONKEY, S.C_REGION_NAME, S.C_PHONE, S.C_ACCTBAL,
    S.C_MKTSEGMENT, S.C_COMMENT, S.LOAD_TIMESTAMP
  );
  RETURN 'CUSTOMER_STREAM consumed and CUSTOMER_SILVER merged';
END;
$$;

CREATE OR REPLACE PROCEDURE SILVER.SP_BRONZE_TO_SILVER_LINEITEM()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO SILVER.LINEITEM_SILVER T
  USING (
    SELECT * EXCLUDE (RN)
    FROM (
      SELECT L.L_ORDERKEY, L.L_LINENUMBER, L.L_PARTKEY,
        P.P_NAME AS L_PART_NAME, P.P_TYPE AS L_PART_TYPE,
        L.L_SUPPKEY, S.S_NAME AS L_SUPPLIER_NAME,
        L.L_QUANTITY, L.L_EXTENDEDPRICE, L.L_DISCOUNT, L.L_TAX,
        L.L_RETURNFLAG, L.L_LINESTATUS, L.L_SHIPDATE, L.L_COMMITDATE,
        L.L_RECEIPTDATE, L.L_SHIPINSTRUCT, L.L_SHIPMODE, L.L_COMMENT,
        ROUND(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT), 2) AS L_NET_PRICE,
        ROUND(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT) * (1 + L.L_TAX), 2) AS L_FINAL_PRICE,
        DATEDIFF('day', L.L_COMMITDATE, L.L_RECEIPTDATE) AS L_SHIP_DELAY_DAYS,
        CURRENT_TIMESTAMP() AS LOAD_TIMESTAMP,
        ROW_NUMBER() OVER (
          PARTITION BY L.L_ORDERKEY, L.L_LINENUMBER ORDER BY L.METADATA$ROW_ID DESC
        ) AS RN
      FROM STAGING.LINEITEM_STREAM L
      LEFT JOIN STAGING.PART P ON L.L_PARTKEY = P.P_PARTKEY
      LEFT JOIN STAGING.SUPPLIER S ON L.L_SUPPKEY = S.S_SUPPKEY
      WHERE L.METADATA$ACTION = 'INSERT'
    )
    WHERE RN = 1
  ) S
  ON T.L_ORDERKEY=S.L_ORDERKEY AND T.L_LINENUMBER=S.L_LINENUMBER
  WHEN MATCHED THEN UPDATE SET
    T.L_PARTKEY=S.L_PARTKEY, T.L_PART_NAME=S.L_PART_NAME,
    T.L_PART_TYPE=S.L_PART_TYPE, T.L_SUPPKEY=S.L_SUPPKEY,
    T.L_SUPPLIER_NAME=S.L_SUPPLIER_NAME, T.L_QUANTITY=S.L_QUANTITY,
    T.L_EXTENDEDPRICE=S.L_EXTENDEDPRICE, T.L_DISCOUNT=S.L_DISCOUNT,
    T.L_TAX=S.L_TAX, T.L_RETURNFLAG=S.L_RETURNFLAG,
    T.L_LINESTATUS=S.L_LINESTATUS, T.L_SHIPDATE=S.L_SHIPDATE,
    T.L_COMMITDATE=S.L_COMMITDATE, T.L_RECEIPTDATE=S.L_RECEIPTDATE,
    T.L_SHIPINSTRUCT=S.L_SHIPINSTRUCT, T.L_SHIPMODE=S.L_SHIPMODE,
    T.L_COMMENT=S.L_COMMENT, T.L_NET_PRICE=S.L_NET_PRICE,
    T.L_FINAL_PRICE=S.L_FINAL_PRICE, T.L_SHIP_DELAY_DAYS=S.L_SHIP_DELAY_DAYS,
    T.LOAD_TIMESTAMP=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    L_ORDERKEY, L_LINENUMBER, L_PARTKEY, L_PART_NAME, L_PART_TYPE,
    L_SUPPKEY, L_SUPPLIER_NAME, L_QUANTITY, L_EXTENDEDPRICE, L_DISCOUNT,
    L_TAX, L_RETURNFLAG, L_LINESTATUS, L_SHIPDATE, L_COMMITDATE,
    L_RECEIPTDATE, L_SHIPINSTRUCT, L_SHIPMODE, L_COMMENT, L_NET_PRICE,
    L_FINAL_PRICE, L_SHIP_DELAY_DAYS, LOAD_TIMESTAMP
  ) VALUES (
    S.L_ORDERKEY, S.L_LINENUMBER, S.L_PARTKEY, S.L_PART_NAME, S.L_PART_TYPE,
    S.L_SUPPKEY, S.L_SUPPLIER_NAME, S.L_QUANTITY, S.L_EXTENDEDPRICE,
    S.L_DISCOUNT, S.L_TAX, S.L_RETURNFLAG, S.L_LINESTATUS, S.L_SHIPDATE,
    S.L_COMMITDATE, S.L_RECEIPTDATE, S.L_SHIPINSTRUCT, S.L_SHIPMODE,
    S.L_COMMENT, S.L_NET_PRICE, S.L_FINAL_PRICE, S.L_SHIP_DELAY_DAYS,
    S.LOAD_TIMESTAMP
  );
  RETURN 'LINEITEM_STREAM consumed and LINEITEM_SILVER merged';
END;
$$;

