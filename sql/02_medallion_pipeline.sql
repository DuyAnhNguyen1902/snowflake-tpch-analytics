-- -----------------------------------------------------------------------------
-- F. Task graph
-- One scheduled root runs every five minutes. Child tasks execute in order so
-- all three streams are consumed before the Gold tables are refreshed.
-- -----------------------------------------------------------------------------
-- Required for safe re-runs: a graph's root must be suspended before tasks are
-- recreated or dependencies are changed.
ALTER TASK IF EXISTS STAGING.TASK_BRONZE_TO_SILVER_ORDERS SUSPEND;
ALTER TASK IF EXISTS STAGING.TASK_BRONZE_TO_SILVER_CUSTOMERS SUSPEND;
ALTER TASK IF EXISTS STAGING.TASK_BRONZE_TO_SILVER_LINEITEM SUSPEND;
ALTER TASK IF EXISTS STAGING.TASK_SILVER_TO_GOLD_CUSTOMER_LTV SUSPEND;
ALTER TASK IF EXISTS STAGING.TASK_SILVER_TO_GOLD_DAILY_SALES SUSPEND;

CREATE OR REPLACE TASK STAGING.TASK_BRONZE_TO_SILVER_ORDERS
  WAREHOUSE = TPCH_WH
  SCHEDULE = '5 MINUTES'
  OVERLAP_POLICY = NO_OVERLAP
  WHEN SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.ORDERS_STREAM')
    OR SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.CUSTOMER_STREAM')
    OR SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.LINEITEM_STREAM')
AS CALL SILVER.SP_BRONZE_TO_SILVER_ORDERS();

CREATE OR REPLACE TASK STAGING.TASK_BRONZE_TO_SILVER_CUSTOMERS
  WAREHOUSE = TPCH_WH
  AFTER STAGING.TASK_BRONZE_TO_SILVER_ORDERS
AS CALL SILVER.SP_BRONZE_TO_SILVER_CUSTOMERS();

CREATE OR REPLACE TASK STAGING.TASK_BRONZE_TO_SILVER_LINEITEM
  WAREHOUSE = TPCH_WH
  AFTER STAGING.TASK_BRONZE_TO_SILVER_CUSTOMERS
AS CALL SILVER.SP_BRONZE_TO_SILVER_LINEITEM();

-- Every task is kept in STAGING because all tasks in a Snowflake task graph
-- must share one schema and owner, even when a task calls a GOLD procedure.
CREATE OR REPLACE TASK STAGING.TASK_SILVER_TO_GOLD_CUSTOMER_LTV
  WAREHOUSE = TPCH_WH
  AFTER STAGING.TASK_BRONZE_TO_SILVER_LINEITEM
AS CALL GOLD.SP_CALCULATE_CUSTOMER_LTV();

CREATE OR REPLACE TASK STAGING.TASK_SILVER_TO_GOLD_DAILY_SALES
  WAREHOUSE = TPCH_WH
  AFTER STAGING.TASK_SILVER_TO_GOLD_CUSTOMER_LTV
AS CALL GOLD.SP_CALCULATE_DAILY_SALES();

-- Resume children first, root last.
ALTER TASK STAGING.TASK_SILVER_TO_GOLD_DAILY_SALES RESUME;
ALTER TASK STAGING.TASK_SILVER_TO_GOLD_CUSTOMER_LTV RESUME;
ALTER TASK STAGING.TASK_BRONZE_TO_SILVER_LINEITEM RESUME;
ALTER TASK STAGING.TASK_BRONZE_TO_SILVER_CUSTOMERS RESUME;
ALTER TASK STAGING.TASK_BRONZE_TO_SILVER_ORDERS RESUME;

-- Execute once immediately for the initial load (no five-minute wait).
