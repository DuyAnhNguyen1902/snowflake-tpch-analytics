SHOW STREAMS IN SCHEMA STAGING;
SELECT SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.ORDERS_STREAM') AS ORDERS_HAS_DATA;
SELECT SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.CUSTOMER_STREAM') AS CUSTOMER_HAS_DATA;
SELECT SYSTEM$STREAM_HAS_DATA('TPCH_ANALYTICS_DB.STAGING.LINEITEM_STREAM') AS LINEITEM_HAS_DATA;

SELECT 'ORDERS_SILVER' TABLE_NAME, COUNT(*) ROW_COUNT FROM SILVER.ORDERS_SILVER
UNION ALL SELECT 'CUSTOMER_SILVER', COUNT(*) FROM SILVER.CUSTOMER_SILVER
UNION ALL SELECT 'LINEITEM_SILVER', COUNT(*) FROM SILVER.LINEITEM_SILVER
UNION ALL SELECT 'CUSTOMER_LTV', COUNT(*) FROM GOLD.CUSTOMER_LTV
UNION ALL SELECT 'DAILY_SALES_SUMMARY', COUNT(*) FROM GOLD.DAILY_SALES_SUMMARY
ORDER BY TABLE_NAME;

SELECT NAME, STATE, SCHEDULE, PREDECESSORS
FROM TABLE(INFORMATION_SCHEMA.TASK_DEPENDENTS(
  TASK_NAME => 'TPCH_ANALYTICS_DB.STAGING.TASK_BRONZE_TO_SILVER_ORDERS',
  RECURSIVE => TRUE
));

SELECT NAME, STATE, SCHEDULED_TIME, QUERY_START_TIME, COMPLETED_TIME,
       RETURN_VALUE, ERROR_CODE, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP()),
  RESULT_LIMIT => 100
))
WHERE DATABASE_NAME = 'TPCH_ANALYTICS_DB'
ORDER BY SCHEDULED_TIME DESC;

